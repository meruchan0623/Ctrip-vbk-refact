export type I18nKey = keyof typeof zhCN;

export function t(key: I18nKey, vars?: Readonly<Record<string, string | number>>): string {
  const s: string = zhCN[key];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, name: string) => {
    const v = vars[name];
    return v === undefined ? m : String(v);
  });
}

export function hasKey(key: string): key is I18nKey {
  return Object.prototype.hasOwnProperty.call(zhCN, key);
}
